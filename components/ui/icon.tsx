export type IconName = keyof typeof glyphs;

export const iconNames = Object.keys(glyphs) as IconName[];

type IconProps = Omit<SVGProps<SVGSVGElement>, "name"> & {
  name: IconName;
  size?: number;
  /** Accessible label. Without one the icon is decorative and hidden from assistive tech. */
  label?: string;
};

export function Icon({ name, size = 24, label, ...props }: IconProps) {
  const glyph: Glyph = glyphs[name];

  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill={glyph.filled ? "currentColor" : "none"}
      stroke={glyph.filled ? "none" : "currentColor"}
      strokeWidth={1.5}
      strokeLinecap="round"
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      {...props}
    >
      {/* Filled glyphs paint the 40% tone first so the solid shapes sit on top */}
      {glyph.filled && glyph.secondary?.map((d) => <path key={d} d={d} opacity={0.4} />)}
      {glyph.primary.map((d) => (
        <path key={d} d={d} fillRule={glyph.filled ? "evenodd" : undefined} />
      ))}
      {!glyph.filled && glyph.secondary?.map((d) => <path key={d} d={d} opacity={0.4} />)}
    </svg>
  );
}

/** True when the icon set has a glyph with this name. */
export function hasIcon(name: string): name is IconName {
  return Object.hasOwn(glyphs, name);
}

/**
 * Renders the named icon when the set has it, otherwise `fallback` (default: an empty
 * slot of the same size). Use for names that come from content or icons not yet exported.
 */
export function MaybeIcon({
  name,
  size = 24,
  fallback,
  ...props
}: Omit<IconProps, "name"> & { name: string; fallback?: ReactNode }) {
  if (hasIcon(name)) return <Icon name={name} size={size} {...props} />;
  if (fallback !== undefined) return <>{fallback}</>;
  return (
    <span
      aria-hidden
      className={props.className}
      style={{ display: "inline-block", flexShrink: 0, width: size, height: size }}
    />
  );
}
